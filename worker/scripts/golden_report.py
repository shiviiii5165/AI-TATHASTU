"""Role-by-role evaluation matrix for the golden profiles (workstream E).

  python scripts/golden_report.py            prints the matrix
  python scripts/golden_report.py --write    also writes docs/engineering/CAREER_INTELLIGENCE_EVALUATION.md

Deterministic: synthetic profiles (tests/golden_profiles.py) through the real engine. No network, no database.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

import golden_profiles as g  # noqa: E402
from intelligence.frameworks import CURRENT_ROLES, DOMAINS, FRAMEWORK_VERSION, FRAMEWORKS, OPEN_QUESTIONS, domain_of  # noqa: E402
from intelligence.career_engine import ENGINE_VERSION  # noqa: E402
from intelligence.reachability import routes  # noqa: E402

SHORT = {"not_enough_evidence": "none", "early": "early", "developing": "devel.", "strong": "strong", "requirements_demonstrated": "demonstr."}


def matrix():
    rows, total_fp, fp_detail = [], 0, []
    for role in CURRENT_ROLES:
        f = FRAMEWORKS[role]
        reqs = f.requirements
        cells = {}
        for name, build in g.PROFILES.items():
            facts, repos = build(role)
            out = g.run(facts, repos, [role])
            a = g.analysis(out, role)["alignment"]
            cells[name] = f"{SHORT[a['state']]} {a['requiredMet']}/{a['required']}"
            bad = g.false_expertise(out)
            total_fp += len(bad)
            fp_detail += [f"{role}/{name}: {b}" for b in bad]
        rows.append({
            "role": role, "label": f.label,
            "domains": len({domain_of(r.competency) for r in reqs}),
            "required": sum(1 for r in reqs if r.required), "supporting": sum(1 for r in reqs if not r.required),
            "notCodeVerifiable": [r.competency for r in reqs if r.required and not routes(r.competency)],
            **cells,
        })
    return rows, total_fp, fp_detail


def render(rows, total_fp, fp_detail) -> str:
    profiles = list(g.PROFILES)
    head = "| Role | Domains | Req | Sup | " + " | ".join(profiles) + " |"
    sep = "|" + "---|" * (4 + len(profiles))
    body = [f"| {r['label']} | {r['domains']} | {r['required']} | {r['supporting']} | " + " | ".join(r[p] for p in profiles) + " |" for r in rows]
    unver = [f"- {r['label']}: {', '.join(r['notCodeVerifiable'])}" for r in rows if r["notCodeVerifiable"]]
    questions = [f"- **{q['id']}** ({q['status']}): {q['question']} {q['note']}" for q in OPEN_QUESTIONS]
    return "\n".join([
        "# Career intelligence: golden evaluation",
        "",
        f"Engine v{ENGINE_VERSION}, framework {FRAMEWORK_VERSION} (DRAFT / UNREVIEWED). Generated by `worker/scripts/golden_report.py` from "
        "synthetic profiles in `worker/tests/golden_profiles.py`; asserted by `worker/tests/test_golden_roles.py`.",
        "",
        "Cells: alignment state and required competencies met. `demonstr.` = requirements adequately demonstrated.",
        "",
        "Profiles: **beginner_claims** skills list only; **resume_inflated** claims plus self-described projects in everything; "
        "**high_activity_low_depth** 12 Python repositories with no dependencies, tests or docs; **contradicted** claims, repositories only tag the skills; "
        "**not_own_code** strong repositories where the student made 1 of 60 commits; **intermediate** one own repository, no tests or CI; "
        "**outdated** the advanced profile pushed ~2.5 years ago; **advanced_practical** four own repositories with tests and CI, no certificates.",
        "",
        head, sep, *body,
        "",
        f"**False-expertise findings across {len(rows)} roles x {len(profiles)} profiles: {total_fp}.** "
        "(A competency marked met, or a skill at Proficient or above, without the evidence the method requires.)",
        *(["", *[f"- {d}" for d in fp_detail]] if fp_detail else []),
        "",
        "## Required competencies no repository can show",
        "",
        "Met on the student's described work and flagged `codeVerifiable: false` (engine v5). They need an assessment we don't run yet.",
        "",
        *unver,
        "",
        f"## Domains ({len(DOMAINS)})",
        "",
        *[f"- **{d['label']}**: {d['description']}" for d in DOMAINS.values()],
        "",
        "## Open research questions",
        "",
        *questions,
        "",
    ])


if __name__ == "__main__":
    rows, fp, detail = matrix()
    text = render(rows, fp, detail)
    print(text)
    if "--write" in sys.argv:
        out = ROOT.parent / "docs" / "engineering" / "CAREER_INTELLIGENCE_EVALUATION.md"
        out.write_text(text, encoding="utf-8")
        print(f"\nwrote {out}")
